import { type AdminEmailContent, adminEmailPlainText } from "@/emails/admin-email-content";
import { AdminEmail } from "@/emails/admin-email-shell";
import { formatEmailTimestamp } from "@/emails/format-timestamp";
import { OWNER_VALUE } from "@/lib/email/owner-vocabulary";

export type SupportReportEvent = {
	contactEmail: string | null;
	message: string | null;
	report: string;
	appVersion: string | null;
	receivedAtIso: string;
};

function supportContent(event: SupportReportEvent): AdminEmailContent {
	const version = event.appVersion ? ` · v${event.appVersion}` : "";
	return {
		// A support report is always the issue: someone asked for help.
		issues: [
			event.contactEmail
				? `A user asked for help. Reply to ${event.contactEmail}.`
				: "A user asked for help but left no reply email.",
		],
		lede: event.contactEmail
			? `Redacted report from the Mac app${version}.`
			: `Redacted report from the Mac app${version}. No reply email.`,
		preview: event.contactEmail
			? `JP the Cat support report · ${event.contactEmail}`
			: "JP the Cat support report",
		sections: [
			{ block: event.message, title: "User note" },
			{
				title: "Contact",
				rows: [
					{ label: "Reply email", value: event.contactEmail ?? OWNER_VALUE.notProvided },
					{ label: "App version", value: event.appVersion ?? OWNER_VALUE.unknown },
					{ label: "Received", value: formatEmailTimestamp(event.receivedAtIso) },
				],
			},
			// Generated by the app; it should carry no prompts, code, transcripts, secrets, or raw paths.
			{ block: event.report, title: "App report" },
		],
		title: "Support report",
	};
}

export function SupportReportEmail({ event }: { event: SupportReportEvent }) {
	return <AdminEmail content={supportContent(event)} />;
}

export function SupportReportPlainText({ event }: { event: SupportReportEvent }) {
	return adminEmailPlainText(supportContent(event));
}
